#!/usr/bin/env node
// Generates src/generated/inlineContent.js for the single-file Hub build: a base64
// map of every file the app loads from public/ at runtime. Base64 also keeps the
// emitted HTML free of literal ``` and </script> sequences.
//
// PDFs are left out (they link to the source repo instead; see
// src/content/inlineContent.js). Dashboard screenshots are 3200px PNGs captured at
// 2x, which alone would exceed Atrium's 10 MB limit, so they are re-encoded as
// 1600px JPEGs here; the thumbnails are already small JPEGs and ship as they are.
// The app keeps referring to the original .png paths.
import { readdirSync, readFileSync, statSync, mkdirSync, writeFileSync } from 'node:fs'
import { join, extname, relative, sep } from 'node:path'
import { fileURLToPath } from 'node:url'
import sharp from 'sharp'

const root = fileURLToPath(new URL('..', import.meta.url))
const pub = join(root, 'public')

const MIME = {
  '.json': 'application/json',
  '.ndjson': 'application/x-ndjson',
  '.md': 'text/markdown',
  '.png': 'image/png',
  '.jpg': 'image/jpeg',
  '.jpeg': 'image/jpeg',
  '.svg': 'image/svg+xml',
  '.txt': 'text/plain',
  '.yml': 'text/yaml',
  '.yaml': 'text/yaml',
}
const EXCLUDE = new Set(['.pdf'])
const SHOT = /^\/screenshots\/[^/]+\.png$/
const SHOT_WIDTH = 1600
const SHOT_QUALITY = 75

function* walk(dir) {
  for (const name of readdirSync(dir).sort()) {
    const p = join(dir, name)
    if (statSync(p).isDirectory()) yield* walk(p)
    else yield p
  }
}

const entries = {}
let total = 0
for (const file of walk(pub)) {
  const ext = extname(file).toLowerCase()
  if (EXCLUDE.has(ext)) continue
  const urlPath = '/' + relative(pub, file).split(sep).join('/')
  if (urlPath === '/favicon.svg') continue
  let buf = readFileSync(file)
  let mime = MIME[ext] || 'application/octet-stream'
  if (SHOT.test(urlPath)) {
    buf = await sharp(buf)
      .resize({ width: SHOT_WIDTH, withoutEnlargement: true })
      .flatten({ background: '#000000' })
      .jpeg({ quality: SHOT_QUALITY, mozjpeg: true })
      .toBuffer()
    mime = 'image/jpeg'
  }
  total += buf.length
  entries[urlPath] = { m: mime, d: buf.toString('base64') }
}

const outDir = join(root, 'src', 'generated')
mkdirSync(outDir, { recursive: true })
writeFileSync(
  join(outDir, 'inlineContent.js'),
  '// AUTO-GENERATED by scripts/generate-inline-content.mjs. Do not edit or commit.\n' +
    'export const CONTENT = ' + JSON.stringify(entries) + '\n',
)
console.log(`inline content: ${Object.keys(entries).length} files, ${(total / 1024 / 1024).toFixed(1)} MB raw`)
