#!/usr/bin/env node
// Generates src/generated/inlineContent.js for the single-file Hub build: a base64
// map of every file the app fetches from public/ at runtime. Base64 keeps the
// emitted HTML free of literal ``` and </script> sequences — the Elastic Hub stores
// the page inside a fenced code block and would truncate on either.
// PDFs are excluded (linked out to GitHub instead); see src/content/inlineContent.js.
import { readdirSync, readFileSync, statSync, mkdirSync, writeFileSync } from 'node:fs'
import { join, extname, relative, sep } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('..', import.meta.url))
const pub = join(root, 'public')

const MIME = {
  '.json': 'application/json',
  '.ndjson': 'application/x-ndjson',
  '.md': 'text/markdown',
  '.png': 'image/png',
  '.jpg': 'image/jpeg',
  '.jpeg': 'image/jpeg',
  '.svg': 'image/svg+xml',
  '.txt': 'text/plain',
  '.yml': 'text/yaml',
  '.yaml': 'text/yaml',
}
const EXCLUDE = new Set(['.pdf'])

function* walk(dir) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name)
    if (statSync(p).isDirectory()) yield* walk(p)
    else yield p
  }
}

const entries = {}
let total = 0
for (const file of walk(pub)) {
  const ext = extname(file).toLowerCase()
  if (EXCLUDE.has(ext)) continue
  const urlPath = '/' + relative(pub, file).split(sep).join('/')
  if (urlPath === '/favicon.svg') continue
  const buf = readFileSync(file)
  total += buf.length
  entries[urlPath] = { m: MIME[ext] || 'application/octet-stream', d: buf.toString('base64') }
}

const outDir = join(root, 'src', 'generated')
mkdirSync(outDir, { recursive: true })
writeFileSync(
  join(outDir, 'inlineContent.js'),
  '// AUTO-GENERATED by scripts/generate-inline-content.mjs — do not edit or commit.\n' +
    'export const CONTENT = ' + JSON.stringify(entries) + '\n',
)
console.log(`inline content: ${Object.keys(entries).length} files, ${(total / 1024 / 1024).toFixed(1)} MB raw`)
